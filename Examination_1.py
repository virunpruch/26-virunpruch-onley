# โจทย์ข้อที่ 1: คำนวณคะแนนเฉลี่ย 3 วิชา
# Input: บรรทัดที่ 1-3 คะแนนวิชาที่ 1, 2, 3 (จำนวนเต็ม)
# Output: คะแนนเฉลี่ย
# ==========================================


# นักเรียนเขียนโค้ดต่อจากบรรทัดนี้
s1 = int(input("คะแนนวิชาที่1 : "))
s2 = int(input("คะแนนวิชาที่2 : "))
s3 = int(input("คะแนนวิชาที่3 : "))
total = s1+s2+s3
a = total/3
print("คะแนนเฉลี่ย :",a)

# โจทย์ข้อที่ 2: ตรวจสอบความสูงสำหรับเล่นเครื่องเล่น
# Input: ความสูงซม. (จำนวนเต็ม)
# Output: พิมพ์ "Can Ride" หากสูงตั้งแต่ 140 ซม. ขึ้นไป หรือ "Cannot Ride" หากน้อยกว่า 140 ซม.
# ==========================================


# นักเรียนเขียนโค้ดต่อจากบรรทัดนี้
height = int(input("ความสูงซม. : "))
if height>140 :
    print("Can Ride")
else :
    print("Cannot Ride")
